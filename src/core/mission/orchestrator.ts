import type {
  ExecutionPlan,
} from "../reasoning/types";

import type {
  Mission,
  MissionSnapshot,
  MissionTask,
} from "./types";

import { MissionEngine } from "./mission-engine";
import { TaskGraphEngine } from "./task-graph";
import {
  composeTrustedWorkerRuntime,
  type WorkerRuntimeComposition,
  type WorkerRuntimeCompositionDependencies,
} from "./worker-runtime-composition";
import type {
  WorkerBrokerOperation,
  WorkerDispatchOutbox,
  WorkerTenantScope,
} from "./worker-database-broker";
import {
  claimAndEnqueueApprovedTask,
  runNextDurableDispatch,
  type ApprovedTaskEnqueueResult,
  type DurableDispatchPollResult,
  type IdempotentDispatchProvider,
} from "./durable-dispatch-worker-contract";
import type { ProviderStatusReader } from "./provider-dispatch-reconciliation";
import {
  assessPersistedMissionRecovery,
  createWorkerBrokerRecoveryEvidenceReader,
  type PersistedMissionRecoveryResult,
  type RecoveryEvidenceReader,
} from "./persisted-recovery-assessment";
import type { TenantScope } from "../state/types";
import type { Evidence } from "../evidence/types";
import type { VerificationRequest, VerificationResult } from "../verification/types";
import type { TrustedSemanticAttestationAuthority } from "../verification/semantic-attestation";
import {
  requireCompleteScope,
  TenantPersistenceError,
  type AsyncTenantPersistenceAdapter,
} from "../persistence/async-tenant-repository";

export class MissionOrchestrator {
  private readonly missionEngine = new MissionEngine();
  private readonly graphEngine = new TaskGraphEngine();

  constructor(
    private readonly workerRuntimeDependencies: WorkerRuntimeCompositionDependencies | null = null,
    private readonly semanticAttestationAuthority: TrustedSemanticAttestationAuthority | null = null,
  ) {}

  /**
   * Explicit worker-only authorization seam. The default application
   * orchestrator remains disconnected and continues using its existing
   * mission/task graph behavior; it never falls back to a human session or
   * silently treats in-memory orchestration as durable worker execution.
   */
  prepareWorkerRuntimeOperation(
    operation: WorkerBrokerOperation,
    now?: () => number,
  ): Promise<WorkerRuntimeComposition> {
    if (!this.workerRuntimeDependencies) {
      return Promise.resolve({
        status: "NOT_CONNECTED",
        missing: "IDENTITY_PROVIDER",
      });
    }

    return composeTrustedWorkerRuntime({
      dependencies: this.workerRuntimeDependencies,
      operation,
      ...(now ? { now } : {}),
    });
  }

  /**
   * Runs one durable outbox item through the guarded worker broker.
   * The owner ID must be generated by the trusted worker process, not by a
   * user request. A disconnected default orchestrator remains fail-closed.
   */
  async runNextWorkerDispatch(input: {
    tenantScope: WorkerTenantScope;
    ownerId: string;
    leaseMilliseconds: number;
    provider: IdempotentDispatchProvider;
    reconciliationProvider?: ProviderStatusReader;
    claimedOutbox?: WorkerDispatchOutbox;
    now?: () => number;
  }): Promise<WorkerRuntimeComposition | DurableDispatchPollResult> {
    const composition = await this.prepareWorkerRuntimeOperation(
      "claim_next_dispatch",
      input.now,
    );
    if (composition.status !== "COMPOSITION_AVAILABLE") return composition;

    const identityProvider = this.workerRuntimeDependencies?.identityProvider;
    if (!identityProvider) {
      return { status: "NOT_CONNECTED", missing: "IDENTITY_PROVIDER" };
    }
    return runNextDurableDispatch({
      broker: composition.broker,
      tenantScope: input.tenantScope,
      ownerId: input.ownerId,
      leaseMilliseconds: input.leaseMilliseconds,
      identityProvider,
      provider: input.provider,
      ...(input.reconciliationProvider ? { reconciliationProvider: input.reconciliationProvider } : {}),
      ...(input.claimedOutbox ? { claimedOutbox: input.claimedOutbox } : {}),
      ...(input.now ? { now: input.now } : {}),
    });
  }

  /**
   * Runs one explicitly selected mission task through claim, approved request
   * binding, outbox enqueue, provider dispatch, fenced outcome and optional
   * reconciliation. This is a single bounded iteration, not a polling loop.
   */
  async runMissionTaskDispatch(input: {
    tenantScope: WorkerTenantScope;
    missionId: string;
    taskId: string;
    ownerId: string;
    leaseMilliseconds: number;
    provider: IdempotentDispatchProvider;
    reconciliationProvider?: ProviderStatusReader;
    now?: () => number;
  }): Promise<WorkerRuntimeComposition | ApprovedTaskEnqueueResult | DurableDispatchPollResult> {
    const composition = await this.prepareWorkerRuntimeOperation("claim_task", input.now);
    if (composition.status !== "COMPOSITION_AVAILABLE") return composition;

    const enqueue = await claimAndEnqueueApprovedTask({
      broker: composition.broker,
      tenantScope: input.tenantScope,
      missionId: input.missionId,
      taskId: input.taskId,
      ownerId: input.ownerId,
      leaseMilliseconds: input.leaseMilliseconds,
    });
    if (enqueue.status !== "ENQUEUED") return enqueue;

    return this.runNextWorkerDispatch({
      tenantScope: input.tenantScope,
      ownerId: input.ownerId,
      leaseMilliseconds: input.leaseMilliseconds,
      provider: input.provider,
      claimedOutbox: enqueue.outbox,
      ...(input.reconciliationProvider ? { reconciliationProvider: input.reconciliationProvider } : {}),
      ...(input.now ? { now: input.now } : {}),
    });
  }

  /**
   * Finds the next dependency-ready task from the caller's tenant-scoped
   * durable mission/task records and executes exactly one bounded worker
   * iteration. The database claim remains authoritative for approval, lease,
   * capability, and tenant checks; this scan is scheduling, not authorization.
   */
  async runNextReadyMissionTaskDispatch(input: {
    persistence: AsyncTenantPersistenceAdapter;
    scope: TenantScope;
    tenantScope: WorkerTenantScope;
    ownerId: string;
    leaseMilliseconds: number;
    provider: IdempotentDispatchProvider;
    reconciliationProvider?: ProviderStatusReader;
    now?: () => number;
  }): Promise<
    WorkerRuntimeComposition |
    ApprovedTaskEnqueueResult |
    DurableDispatchPollResult |
    { status: "NO_READY_TASK" } |
    { status: "SCHEDULER_SCAN_INCOMPLETE"; missionCount: number; taskCount: number } |
    { status: "NOT_CONNECTED"; missing: "TENANT_PERSISTENCE" }
  > {
    // Resolve trusted workload identity and the live principal registry
    // before reading tenant scheduling metadata. The claim path re-authorizes
    // immediately before every broker operation.
    const composition = await this.prepareWorkerRuntimeOperation("claim_task", input.now);
    if (composition.status !== "COMPOSITION_AVAILABLE") return composition;

    const scope = input.scope;
    requireCompleteScope(scope);
    if (
      scope.organizationId !== input.tenantScope.organizationId ||
      scope.workspaceId !== input.tenantScope.workspaceId ||
      scope.userId !== input.tenantScope.userId
    ) {
      throw new TenantPersistenceError("INVALID_TENANT_SCOPE", "Scheduler scan and worker claim must use the same tenant scope.");
    }

    const [missions, tasks] = await Promise.all([
      input.persistence.list<Mission>(scope, { entityType: "MISSION", limit: 200 }),
      input.persistence.list<MissionTask>(scope, { entityType: "TASK", limit: 1000 }),
    ]);
    // list() exposes a hard limit but no cursor/total count. Reaching either
    // limit means the candidate set may be truncated; never report NO_READY_TASK
    // or dispatch from an incomplete scheduler snapshot.
    if (missions.length >= 200 || tasks.length >= 1000) {
      return {
        status: "SCHEDULER_SCAN_INCOMPLETE",
        missionCount: missions.length,
        taskCount: tasks.length,
      };
    }

    const tasksByMission = new Map<string, MissionTask[]>();
    for (const record of tasks) {
      const task = record.data;
      const group = tasksByMission.get(task.missionId) ?? [];
      group.push(task);
      tasksByMission.set(task.missionId, group);
    }

    const candidates = missions
      .filter((record) => record.data.status === "READY" || record.data.status === "RUNNING")
      .flatMap((record) => {
        const missionTasks = tasksByMission.get(record.data.id) ?? [];
        const byId = new Map(missionTasks.map((task) => [task.id, task]));
        return missionTasks
          .filter((task) =>
            (task.status === "PENDING" || task.status === "READY") &&
            task.dependencyIds.every((dependencyId) => byId.get(dependencyId)?.status === "COMPLETED")
          )
          .map((task) => ({ mission: record.data, task }));
      })
      .sort((left, right) =>
        left.mission.createdAt.localeCompare(right.mission.createdAt) ||
        left.task.order - right.task.order ||
        left.task.id.localeCompare(right.task.id)
      );

    const candidate = candidates[0];
    if (!candidate) return { status: "NO_READY_TASK" };

    return this.runMissionTaskDispatch({
      tenantScope: input.tenantScope,
      missionId: candidate.mission.id,
      taskId: candidate.task.id,
      ownerId: input.ownerId,
      leaseMilliseconds: input.leaseMilliseconds,
      provider: input.provider,
      ...(input.reconciliationProvider ? { reconciliationProvider: input.reconciliationProvider } : {}),
      ...(input.now ? { now: input.now } : {}),
    });
  }

  /**
   * Exposes the persisted crash-recovery assessment through the orchestrator.
   * This is deliberately read-only: it never retries, dispatches, or changes
   * mission/task state. Ambiguous external side effects remain review-gated.
   */
  async assessDurableMissionRecovery(input: {
    scope: TenantScope & { userId: string };
    persistence: AsyncTenantPersistenceAdapter;
    missionId: string;
    evidenceReader?: RecoveryEvidenceReader;
  }): Promise<PersistedMissionRecoveryResult> {
    requireCompleteScope(input.scope);
    return assessPersistedMissionRecovery(
      input.scope,
      input.missionId,
      input.persistence,
      input.evidenceReader,
    );
  }

  /**
   * Runs the read-only persisted recovery assessment through the authenticated
   * worker broker. The worker principal and tenant tuple must match the live
   * registry snapshot; evidence reads are re-authorized by the broker facade.
   */
  async assessWorkerMissionRecovery(input: {
    scope: TenantScope & { userId: string };
    tenantScope: WorkerTenantScope;
    persistence: AsyncTenantPersistenceAdapter;
    missionId: string;
    now?: () => number;
  }): Promise<WorkerRuntimeComposition | PersistedMissionRecoveryResult> {
    requireCompleteScope(input.scope);
    if (input.scope.organizationId !== input.tenantScope.organizationId ||
        input.scope.workspaceId !== input.tenantScope.workspaceId ||
        input.scope.userId !== input.tenantScope.userId) {
      throw new TenantPersistenceError(
        "INVALID_TENANT_SCOPE",
        "Recovery assessment and worker evidence reader must use the same tenant scope.",
      );
    }
    const composition = await this.prepareWorkerRuntimeOperation(
      "list_reconciliation_evidence",
      input.now,
    );
    if (composition.status !== "COMPOSITION_AVAILABLE") return composition;
    if (composition.registration.principalId !== input.tenantScope.workerPrincipalId) {
      return { status: "DENIED", reason: "PRINCIPAL_NOT_AUTHORIZED" };
    }
    const evidenceReader = createWorkerBrokerRecoveryEvidenceReader(
      composition.broker,
      input.tenantScope,
      input.scope,
    );
    return this.assessDurableMissionRecovery({
      scope: input.scope,
      persistence: input.persistence,
      missionId: input.missionId,
      evidenceReader,
    });
  }

  /**
   * Applies a mission-engine task transition and persists both task and
   * aggregate mission state with version-checked writes in one transaction.
   * A rejected graph/transition or stale version rolls back the whole change.
   */
  async transitionTaskDurable(
    input: {
      scope: TenantScope;
      persistence: AsyncTenantPersistenceAdapter;
      missionId: string;
      taskId: string;
      status: MissionTask["status"];
      /** Required when a verification-gated task is being completed. */
      verificationRequestId?: string;
    },
  ): Promise<MissionSnapshot> {
    const scope = input.scope;
    requireCompleteScope(scope);
    return input.persistence.transaction(scope, async (transaction) => {
      const missionRecord = await transaction.get<Mission>(
        scope, "MISSION", input.missionId,
      );
      if (!missionRecord) throw new TenantPersistenceError("RECORD_NOT_FOUND", "Mission record was not found.");

      const taskRecords = await Promise.all(
        missionRecord.data.taskIds.map((id) =>
          transaction.get<MissionTask>(scope, "TASK", id),
        ),
      );
      if (taskRecords.some((record) => !record)) {
        throw new TenantPersistenceError("RECORD_NOT_FOUND", "Mission task graph is incomplete in durable storage.");
      }

      const records = taskRecords.filter((record): record is NonNullable<typeof record> => Boolean(record));
      const tasks = records.map((record) => record.data);
      const targetTask = tasks.find((task) => task.id === input.taskId);
      if (!targetTask) {
        throw new TenantPersistenceError("RECORD_NOT_FOUND", "Mission task was not found in its declared graph.");
      }

      if (input.status === "COMPLETED" && targetTask.verificationRequired) {
        if (!this.semanticAttestationAuthority || !input.verificationRequestId?.trim()) {
          throw new TenantPersistenceError(
            "INVALID_RECORD_DATA",
            "Trusted semantic verification authority and an exact verification request are required.",
          );
        }

        const requestId = input.verificationRequestId.trim();
        const [requestRecord, resultRecord] = await Promise.all([
          transaction.get<VerificationRequest>(scope, "VERIFICATION_REQUEST", requestId),
          transaction.get<VerificationResult>(scope, "VERIFICATION", requestId),
        ]);
        if (!requestRecord || !resultRecord ||
            requestRecord.id !== requestId || requestRecord.data.id !== requestId ||
            requestRecord.data.missionId !== input.missionId ||
            requestRecord.data.taskId !== input.taskId ||
            resultRecord.id !== requestId || resultRecord.data.id !== requestId ||
            resultRecord.data.requestId !== requestId ||
            resultRecord.data.status !== "PASSED" ||
            !resultRecord.data.attestation) {
          throw new TenantPersistenceError(
            "INVALID_RECORD_DATA",
            "A matching persisted PASSED result with signed verifier attestation is required.",
          );
        }

        const request = requestRecord.data;
        const persistedResult = resultRecord.data;
        const attestation = persistedResult.attestation;
        const evidenceIds = attestation.payload.evidenceIds;
        if (!Array.isArray(evidenceIds) || evidenceIds.length === 0 ||
            JSON.stringify([...persistedResult.evidenceIds].sort()) !==
              JSON.stringify([...evidenceIds].sort()) ||
            persistedResult.confidence !== attestation.payload.confidence ||
            persistedResult.summary !== attestation.payload.summary ||
            JSON.stringify([...persistedResult.passedCriteria].sort()) !==
              JSON.stringify([...attestation.payload.passedCriteria].sort()) ||
            JSON.stringify([...persistedResult.failedCriteria].sort()) !==
              JSON.stringify([...attestation.payload.failedCriteria].sort()) ||
            JSON.stringify([...persistedResult.partialCriteria].sort()) !==
              JSON.stringify([...attestation.payload.partialCriteria].sort()) ||
            attestation.payload.outcome !== "PASSED") {
          throw new TenantPersistenceError(
            "INVALID_RECORD_DATA",
            "Persisted verification result does not match its signed attestation.",
          );
        }

        const evidenceRecords = await Promise.all(
          evidenceIds.map((id) => transaction.get<Evidence>(scope, "EVIDENCE", id)),
        );
        if (evidenceRecords.some((record, index) =>
          !record || record.id !== evidenceIds[index] ||
          record.data.id !== evidenceIds[index] ||
          record.data.verificationRequestId !== requestId ||
          record.data.missionId !== input.missionId ||
          record.data.taskId !== input.taskId ||
          (record.data.executionRequestId || undefined) !==
            (request.executionRequestId || undefined)
        )) {
          throw new TenantPersistenceError(
            "INVALID_RECORD_DATA",
            "Signed verification evidence is missing or no longer matches the task scope.",
          );
        }

        const attestationCheck = this.semanticAttestationAuthority.verify({
          attestation,
          scope,
          request,
          evidenceIds,
        });
        if (attestationCheck.status !== "VERIFIED" ||
            attestationCheck.payload.outcome !== "PASSED") {
          throw new TenantPersistenceError(
            "INVALID_RECORD_DATA",
            "Trusted semantic verifier attestation is invalid or does not pass all required criteria.",
          );
        }
      }

      const transition = this.missionEngine.updateTaskStatus(
        missionRecord.data, tasks, input.taskId, input.status,
      );
      const previousTask = records.find((record) => record.id === input.taskId);
      const nextTask = transition.tasks.find((task) => task.id === input.taskId);
      if (!previousTask || !nextTask) {
        throw new TenantPersistenceError("RECORD_NOT_FOUND", "Mission task was not found in its declared graph.");
      }

      if (JSON.stringify(previousTask.data) !== JSON.stringify(nextTask)) {
        await transaction.update(
          scope, "TASK", input.taskId, previousTask.version, nextTask,
        );
      }
      if (JSON.stringify(missionRecord.data) !== JSON.stringify(transition.mission)) {
        await transaction.update(
          scope, "MISSION", input.missionId, missionRecord.version, transition.mission,
        );
      }
      return {
        mission: transition.mission,
        graph: this.graphEngine.buildGraph(transition.tasks),
      };
    });
  }

  /**
   * Creates the mission and all task rows atomically under the exact verified
   * tenant principal. This adapter must be a real transactional store in
   * production; the in-memory adapter is suitable only for contract tests.
   */
  async createDurable(
    plan: ExecutionPlan,
    scope: TenantScope,
    persistence: AsyncTenantPersistenceAdapter,
  ): Promise<MissionSnapshot> {
    requireCompleteScope(scope);
    const snapshot = this.create(plan);
    await persistence.transaction(scope, async (transaction) => {
      await transaction.create(scope, "MISSION", snapshot.mission.id, snapshot.mission);
      for (const task of snapshot.graph.tasks) {
        await transaction.create(scope, "TASK", task.id, task);
      }
    });
    return snapshot;
  }

  create(plan: ExecutionPlan): MissionSnapshot {
    const mission = this.missionEngine.createMission(plan);

    const tasks: MissionTask[] = plan.steps.map(
      (step, index) => ({
        id: mission.taskIds[index],
        missionId: mission.id,
        action: step.action,
        title: step.title,
        description: step.description,
        targetReference: step.targetReference,
        status: "PENDING",
        dependencyIds:
          index === 0
            ? []
            : [mission.taskIds[index - 1]],
        dependentTaskIds: [],
        order: step.order,
        retryCount: 0,
        maxRetries: 3,
        requiresApproval: step.requiresApproval,
        verificationRequired: step.verificationRequired,
        createdAt: new Date().toISOString(),
        updatedAt: new Date().toISOString(),
      }),
    );

    const graph = this.graphEngine.buildGraph(tasks);

    return {
      mission,
      graph,
    };
  }
}
